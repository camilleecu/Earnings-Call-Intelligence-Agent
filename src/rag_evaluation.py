import json
import os
from typing import Any, Literal

from dotenv import load_dotenv
from google import genai
from google.genai import types
from pydantic import BaseModel, Field

load_dotenv()

GEMINI_API_KEY = os.getenv("GEMINI_API_KEY")

if not GEMINI_API_KEY:
    raise RuntimeError("GEMINI_API_KEY is not set")

judge_client = genai.Client(api_key=GEMINI_API_KEY)


class RAGAnswerEvaluation(BaseModel):
    score: Literal["good", "bad"] = Field(
        description=(
            "good only if the RAG answer is correct, sufficiently complete, "
            "and directly answers the question"
        )
    )
    failure_type: Literal[
        "none",
        "wrong_fact",
        "missing_key_information",
        "unsupported_claim",
        "not_answered",
        "wrong_company_or_period",
    ] = Field(
        description="The main reason for a bad answer; none if good."
    )
    reasoning: str = Field(
        description="A concise explanation of the verdict."
    )


JUDGE_INSTRUCTIONS = """
You are a strict evaluator of answers to earnings-call transcript questions.

You receive:
1. A question
2. A human-written reference answer
3. An answer generated by a RAG assistant

Determine whether the RAG answer is good or bad.

Mark good only if the RAG answer:
- Directly answers the question
- Is factually consistent with the reference answer
- Includes the important requested figures, periods, guidance, or drivers
- Does not introduce material unsupported or contradictory claims

Mark bad if it:
- Uses an incorrect number, period, company, segment, or factual claim
- Omits an important part of a multi-part question
- Is materially vague where the reference answer is specific
- Says it does not know despite a sufficient reference answer
- Adds a material unsupported assertion

Judge correctness and completeness, not writing style.
Return JSON matching the required schema.
""".strip()


JUDGE_PROMPT = """
Question:
{query}

Reference answer:
{reference_answer}

RAG answer:
{rag_answer}
""".strip()


def judge_rag_answer(
    record: dict[str, Any],
    model: str = "gemini-2.5-flash",
) -> RAGAnswerEvaluation:
    """Evaluate one RAG answer against its reference answer."""

    prompt = JUDGE_PROMPT.format(
        query=record["query"],
        reference_answer=record["reference_answer"],
        rag_answer=record["rag_answer"],
    )

    response = judge_client.models.generate_content(
        model=model,
        contents=prompt,
        config=types.GenerateContentConfig(
            system_instruction=JUDGE_INSTRUCTIONS,
            temperature=0,
            response_mime_type="application/json",
            response_schema=RAGAnswerEvaluation,
        ),
    )

    return RAGAnswerEvaluation.model_validate_json(response.text)